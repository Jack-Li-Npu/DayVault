import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, '..');
const skillRoot = resolve(projectRoot, 'AI/Skills/dayvault-goal-planner');
const outputPath = resolve(projectRoot, 'supabase/functions/_shared/dayvault-goal-planner.bundle.ts');

const skill = await readFile(resolve(skillRoot, 'SKILL.md'), 'utf8');
const voice = await readFile(resolve(projectRoot, 'AI/Editorial/voice.md'), 'utf8');
const plannerReferencePaths = [
  'references/scheduling-policy.md',
  'references/domain-playbooks.md',
  'references/planner-contract.md',
];
const plannerReferences = await Promise.all(
  plannerReferencePaths.map((path) => readFile(resolve(skillRoot, path), 'utf8')),
);
const schemaDocument = JSON.parse(await readFile(resolve(skillRoot, 'references/output-schema.json'), 'utf8'));
const versionMatch = skill.match(/version:\s*([^\s]+)/);
const version = versionMatch?.[1];
if (!version) throw new Error('Missing skill version: dayvault-goal-planner');
const instructions = [skill, ...plannerReferences, voice].join('\n\n');

const generated = `// Generated by Scripts/bundle-ai-skill.mjs. Do not edit directly.\n` +
  `export const skillVersion = ${JSON.stringify(version)};\n` +
  `export const plannerInstructions = ${JSON.stringify(instructions)};\n` +
  `export const plannerOutputSchema = ${JSON.stringify(schemaDocument.schema, null, 2)} as const;\n`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated);
const promptPath = resolve(skillRoot, 'PROMPT.zh-CN.md');
await mkdir(dirname(promptPath), { recursive: true });
await writeFile(promptPath, instructions);
console.log(`Bundled DayVault planner skill ${version}`);

const operationBundles = [
  { name: 'dayvault-achievement-designer', policy: 'rules.md', schema: 'output-schema.json', operation: 'designAchievements' },
  { name: 'dayvault-companion', policy: 'rules.md', schema: 'output-schema.json', operation: 'companionReply' },
  { name: 'dayvault-goal-planner', policy: 'adjustment-policy.md', schema: 'adjustment-schema.json', operation: 'suggestAdjustment' },
];
const journeyBundles = {};
for (const bundle of operationBundles) {
  const directory = resolve(projectRoot, 'AI/Skills', bundle.name);
  const [entry, rules, responseSchema] = await Promise.all([
    readFile(resolve(directory, 'SKILL.md'), 'utf8'),
    readFile(resolve(directory, 'references', bundle.policy), 'utf8'),
    readFile(resolve(directory, 'references', bundle.schema), 'utf8'),
  ]);
  const bundleVersion = entry.match(/version:\s*([^\s]+)/)?.[1];
  if (!bundleVersion) throw new Error(`Missing skill version: ${bundle.name}`);
  journeyBundles[bundle.operation] = {
    version: bundleVersion,
    instructions: `${entry}\n\n${rules}\n\n${voice}`,
    schema: JSON.parse(responseSchema).schema,
  };
}
await writeFile(resolve(projectRoot, 'supabase/functions/_shared/dayvault-journey.bundle.ts'),
  '// Generated by Scripts/bundle-ai-skill.mjs. Do not edit directly.\n' +
  `export const journeyBundles = ${JSON.stringify(journeyBundles, null, 2)} as const;\n`);
console.log(`Bundled DayVault journey operations: ${Object.keys(journeyBundles).join(', ')}`);
